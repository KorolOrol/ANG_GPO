namespace StructuredNarrative.Enum
{
    /// <summary>
    /// Фаза нарратива (акт).
    /// Функции Проппа группируются по актам классической драматургии.
    /// </summary>
    public enum NarrativePhase
    {
        /// <summary>
        /// Акт I — Экспозиция и Завязка.
        /// Знакомство с миром, персонажами, установление запретов и их нарушение.
        /// Функции Проппа: Отлучка → Посредничество (α ... В)
        /// </summary>
        Setup,

        /// <summary>
        /// Акт II — Развитие и Кульминация.
        /// Противодействие, испытания, борьба и победа.
        /// Функции Проппа: Противодействие → Победа (С ... J)
        /// </summary>
        Confrontation,

        /// <summary>
        /// Акт III — Развязка.
        /// Ликвидация беды, возвращение, узнавание, воцарение.
        /// Функции Проппа: Ликвидация → Свадьба (K ... С*)
        /// </summary>
        Resolution
    }
}