namespace StructuredNarrative.Enum
{
    /// <summary>
    /// Архетипические роли действующих лиц по В.Я. Проппу.
    /// </summary>
    public enum ProppRoleType
    {
        /// <summary>
        /// Герой — персонаж, совершающий путешествие и подвиг
        /// </summary>
        Hero,

        /// <summary>
        /// Антагонист (Вредитель) — противостоит герою
        /// </summary>
        Villain,

        /// <summary>
        /// Даритель — испытывает героя и снаряжает волшебным средством
        /// </summary>
        Donor,

        /// <summary>
        /// Помощник — помогает герою в пути и борьбе
        /// </summary>
        Helper,

        /// <summary>
        /// Искомый персонаж (Царевна) — цель поиска героя
        /// </summary>
        SoughtPerson,

        /// <summary>
        /// Отправитель — посылает героя на подвиг, сообщает о беде
        /// </summary>
        Dispatcher,

        /// <summary>
        /// Ложный герой — присваивает себе заслуги героя
        /// </summary>
        FalseHero
    }
}